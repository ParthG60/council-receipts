# -------------------------------------------------------------------- corpus ---
def _load_raw_corpus(id2ons):
    """Load and filter the full corpus once. Returns DataFrame."""
    frames = []
    for i in range(1, 8):
        df = read_shard_csv(ROOT / f"data_fy{i}" / "doc_topics.csv")
        if df is not None:
            frames.append(df)
    for d in sorted(ENG_DIR.glob("c*/doc_topics.csv")):
        df = read_shard_csv(d)
        if df is not None:
            frames.append(df)
    if not frames:
        return None
    corpus = pd.concat(frames, ignore_index=True)
    if "committee" in corpus.columns:
        corpus = corpus[~corpus["committee"].str.contains(NOTICE_PATTERN, na=False)]
    for t in TOPICS:
        if t not in corpus.columns:
            corpus[t] = 0
    corpus["ons_code"] = corpus["council_id"].map(id2ons)
    corpus = corpus[corpus["ons_code"].notna()]
    return corpus


def load_corpus_by_ons(id2ons):
    """{ons_code: {topic: pct}} — aggregate topic shares per council."""
    corpus = _load_raw_corpus(id2ons)
    if corpus is None:
        return {}
    sums = corpus.groupby("ons_code")[TOPICS].sum()
    shares = {}
    for code, row in sums.iterrows():
        total = row.sum()
        if total > 0:
            shares[code] = (row / total * 100).round(1).to_dict()
    return shares


def corpus_window(id2ons):
    """Human-readable date span + document count of the loaded discussion corpus."""
    corpus = _load_raw_corpus(id2ons)
    if corpus is None or corpus.empty:
        return None
    d = pd.to_datetime(corpus["date"], errors="coerce").dropna()
    if d.empty:
        return None
    lo, hi = d.min(), d.max()
    return {
        "from": lo.date().isoformat(),
        "to": hi.date().isoformat(),
        "label": f"{lo.strftime('%b %Y')} – {hi.strftime('%b %Y')}",
        "docs": int(len(corpus)),
    }


def load_corpus_momentum(id2ons):
    """Monthly topic shares per council for momentum tracking.
    Returns {ons_code: {months: [str], series: {topic: [pct]}, changes: [...]}}.
    Each council also gets min_doc_count for the frontend to assess reliability."""
    corpus = _load_raw_corpus(id2ons)
    if corpus is None or corpus.empty:
        return {}

    # Extract month from ISO date string (first 7 chars: YYYY-MM)
    corpus["month"] = corpus["date"].str[:7]
    # Drop rows with unparseable dates
    corpus = corpus[corpus["month"].notna() & (corpus["month"].str.match(r"\d{4}-\d{2}"))]

    # Aggregate topic hits per (ons_code, month)
    agg_dict = {"doc_id": "count"}
    for t in TOPICS:
        agg_dict[t] = "sum"
    monthly = corpus.groupby(["ons_code", "month"]).agg(agg_dict).rename(columns={"doc_id": "doc_count"})
    monthly = monthly.reset_index()

    # Build per-council structures
    momentum = {}
    for (code, month), row in monthly.groupby(["ons_code", "month"], sort=False).first().iterrows():
        # Prefer the iterrows() output since reset_index may not work cleanly with groupby
        pass

    # Simpler: iterate reset_index rows
    by_code = {}
    for _, row in monthly.iterrows():
        code = row["ons_code"]
        month = row["month"]
        mth_data = {"doc_count": int(row["doc_count"])}
        total = sum(row[t] for t in TOPICS)
        if total > 0:
            mth_data["shares"] = {t: round(row[t] / total * 100, 1) for t in TOPICS if row[t] > 0}
        else:
            mth_data["shares"] = {}
        by_code.setdefault(code, {})[month] = mth_data

    # Compute momentum trends for each council
    MIN_DOCS_PER_WINDOW = 5
    for code, trends in by_code.items():
        months = sorted(trends.keys())
        if len(months) < 4:
            continue

        # Recent = last 2 months, Prior = 2 before that
        recent_months = months[-2:]
        prior_months = months[-4:-2]

        # Aggregate topic hits across each window
        recent_agg = {}
        recent_docs = 0
        for m in recent_months:
            for t, v in trends[m]["shares"].items():
                recent_agg[t] = recent_agg.get(t, 0) + v
            recent_docs += trends[m]["doc_count"]

        prior_agg = {}
        prior_docs = 0
        for m in prior_months:
            for t, v in trends[m]["shares"].items():
                prior_agg[t] = prior_agg.get(t, 0) + v
            prior_docs += trends[m]["doc_count"]

        if recent_docs < MIN_DOCS_PER_WINDOW or prior_docs < MIN_DOCS_PER_WINDOW:
            continue

        n_recent = len(recent_months)
        n_prior = len(prior_months)
        recent_avg = {t: v / n_recent for t, v in recent_agg.items()}
        prior_avg = {t: v / n_prior for t, v in prior_agg.items()}

        changes = []
        for topic in TOPICS:
            r = recent_avg.get(topic, 0.0)
            p = prior_avg.get(topic, 0.0)
            change = round(r - p, 1)
            direction = "rising" if change > 1.0 else ("declining" if change < -1.0 else "stable")
            changes.append({
                "topic": topic,
                "change_pp": change,
                "recent_avg": round(r, 1),
                "prior_avg": round(p, 1),
                "direction": direction,
            })
        changes.sort(key=lambda x: -abs(x["change_pp"]))

        # Series data for the line chart: one array per topic across months
        series = {}
        for topic in TOPICS:
            vals = [trends[m]["shares"].get(topic, 0.0) for m in months]
            series[topic] = vals

        momentum[code] = {
            "months": months,
            "series": series,
            "changes": changes,
            "min_doc_count": min(trends[m]["doc_count"] for m in months),
        }

    return momentum


