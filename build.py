def read_shard_csv(path):
    if not path.exists():
        return None
    try:
        df = pd.read_csv(path)
    except (pd.errors.EmptyDataError, pd.errors.ParserError, OSError, ValueError) as e:
        print(f"  skipping incomplete shard {path}: {e}")
        return None
    return None if df.empty else df


